export function clone(o) { return JSON.parse(JSON.stringify(o)); }

export function deepMerge(d, s) {
  for (const k in s) {
    if (s[k] && typeof s[k] === 'object' && !Array.isArray(s[k]) && d[k] && typeof d[k] === 'object' && !Array.isArray(d[k])) {
      deepMerge(d[k], s[k]);
    } else {
      d[k] = Array.isArray(s[k]) ? s[k].slice() : s[k];
    }
  }
  return d;
}

export function getPath(o, p) { return p.split('.').reduce((a, k) => a == null ? undefined : a[k], o); }

export function setPath(o, p, v) {
  const ks = p.split('.');
  const last = ks.pop();
  ks.reduce((a, k) => a[k], o)[last] = v;
}

